import { z } from "zod";

export const difficultySchema = z.enum(["easy", "medium", "hard"]);
export type Difficulty = z.infer<typeof difficultySchema>;

export const difficultyLabels: Record<Difficulty, string> = {
  easy: "Warm",
  medium: "Realistic",
  hard: "Adversarial",
};

export const difficultyHelp: Record<Difficulty, string> = {
  easy: "Raises one objection, accepts a clear rationale. Good for a first run.",
  medium:
    "Challenges unsupported claims and asks follow-ups. Reads as a real counterpart.",
  hard:
    "Demands evidence and specifics, rarely concedes, and will issue an ultimatum.",
};

export type Role = "user" | "counterpart";

export interface Turn {
  role: Role;
  text: string;
  at: number;
}

export const transcriptTurnSchema = z.object({
  role: z.enum(["user", "counterpart"]),
  text: z.string().trim().min(1).max(4000),
});

/* ------------------------------------------------------------------ */
/* Scenarios                                                           */
/* ------------------------------------------------------------------ */

export const counterpartPublicSchema = z.object({
  name: z.string().min(1).max(80),
  role: z.string().min(1).max(120),
  org: z.string().min(1).max(120),
  initials: z.string().min(1).max(4),
  accentLabel: z.string().min(1).max(120),
  visibleProfile: z.array(z.string().min(1).max(300)).min(1).max(6),
});
export type CounterpartPublic = z.infer<typeof counterpartPublicSchema>;

export const briefingSchema = z.object({
  situation: z.string().min(1).max(600),
  yourGoal: z.string().min(1).max(600),
  stakes: z.string().min(1).max(600),
});
export type Briefing = z.infer<typeof briefingSchema>;

export const voiceRefSchema = z.object({
  id: z.string().min(1).max(80),
  name: z.string().min(1).max(60),
});

export const publicScenarioSchema = z.object({
  id: z.string().min(1).max(64),
  title: z.string().min(1).max(120),
  category: z.string().min(1).max(60),
  tagline: z.string().min(1).max(240),
  counterpart: counterpartPublicSchema,
  voice: voiceRefSchema,
  briefing: briefingSchema,
});
export type PublicScenario = z.infer<typeof publicScenarioSchema>;

export const scenarioEngineSchema = z.object({
  persona: z.string().min(1).max(2000),
  hiddenGoal: z.string().min(1).max(600),
  objections: z.array(z.string().min(1).max(400)).min(1).max(8),
  boundaries: z.string().min(1).max(600),
  knowledge: z.string().min(1).max(800),
  stopping: z.string().min(1).max(600),
});
export type ScenarioEngine = z.infer<typeof scenarioEngineSchema>;

export const customScenarioSchema = z.object({
  scenario: publicScenarioSchema,
  engine: scenarioEngineSchema,
});
export type CustomScenario = z.infer<typeof customScenarioSchema>;

/** Generated by the LLM before a custom session, minus the engine split. */
export const generatedScenarioSchema = z.object({
  title: z.string().min(1).max(120),
  category: z.string().min(1).max(60),
  tagline: z.string().min(1).max(240),
  counterpart: counterpartPublicSchema,
  voiceId: z.string().min(1).max(80),
  briefing: briefingSchema,
  engine: scenarioEngineSchema,
});

export const scenarioRequestSchema = z.object({
  brief: z.string().trim().min(10).max(2000),
  rigor: z.coerce.number().int().min(1).max(3),
});
export type ScenarioRequest = z.infer<typeof scenarioRequestSchema>;

/* ------------------------------------------------------------------ */
/* Chat + evaluation                                                   */
/* ------------------------------------------------------------------ */

export const chatRequestSchema = z.object({
  scenarioId: z.string().trim().min(1).max(64),
  difficulty: difficultySchema,
  transcript: z.array(transcriptTurnSchema).max(60),
  customScenario: customScenarioSchema.optional(),
});
export type ChatRequest = z.infer<typeof chatRequestSchema>;

export const evaluateRequestSchema = z.object({
  scenarioId: z.string().trim().min(1).max(64),
  difficulty: difficultySchema,
  transcript: z.array(transcriptTurnSchema).min(1).max(80),
  customScenario: customScenarioSchema.optional(),
});
export type EvaluateRequest = z.infer<typeof evaluateRequestSchema>;

export const reportSchema = z.object({
  verdict: z.enum(["strong", "solid", "developing"]),
  headline: z.string().min(1).max(200),
  overall: z.string().min(1).max(1200),
  strengths: z
    .array(
      z.object({
        point: z.string().min(1).max(400),
        evidence: z.string().min(1).max(600),
      }),
    )
    .max(6),
  missedOpportunities: z
    .array(
      z.object({
        point: z.string().min(1).max(400),
        evidence: z.string().min(1).max(600),
        better: z.string().min(1).max(600),
      }),
    )
    .max(6),
  weakAnswers: z
    .array(
      z.object({
        quote: z.string().min(1).max(600),
        why: z.string().min(1).max(600),
        alternative: z.string().min(1).max(600),
      }),
    )
    .max(6),
  pushback: z
    .array(
      z.object({
        counterpart: z.string().min(1).max(600),
        yourResponse: z.string().min(1).max(600),
        assessment: z.string().min(1).max(600),
      }),
    )
    .max(6),
  nextSteps: z.array(z.string().min(1).max(400)).min(1).max(6),
});
export type Report = z.infer<typeof reportSchema>;

/* ------------------------------------------------------------------ */
/* Live coaching telemetry                                             */
/* ------------------------------------------------------------------ */

export const coachRequestSchema = z.object({
  scenarioId: z.string().trim().min(1).max(64),
  difficulty: difficultySchema,
  transcript: z.array(transcriptTurnSchema).min(1).max(80),
  customScenario: customScenarioSchema.optional(),
});
export type CoachRequest = z.infer<typeof coachRequestSchema>;

export const coachResponseSchema = z.object({
  hint: z.string().min(1).max(400),
  leverage: z.number().int().min(0).max(100),
  talkListenYou: z.number().int().min(0).max(100),
  talkListenThem: z.number().int().min(0).max(100),
  assertiveness: z.number().int().min(0).max(100),
  objectionsSolved: z.number().int().min(0).max(20),
  objectionsTotal: z.number().int().min(0).max(20),
});
export type CoachReport = z.infer<typeof coachResponseSchema>;

/* ------------------------------------------------------------------ */
/* Persistence                                                        */
/* ------------------------------------------------------------------ */

export interface StoredSession {
  id: string;
  scenarioId: string;
  scenarioTitle: string;
  counterpartName: string;
  difficulty: Difficulty;
  startedAt: number;
  endedAt: number;
  transcript: Turn[];
  report?: Report | null;
  customScenario?: CustomScenario | null;
}
